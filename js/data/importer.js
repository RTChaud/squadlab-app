// Reads and validates the two kinds of file SquadLab accepts:
//   • FM snapshot — a dated JSON produced by the Python save extractor
//   • App backup  — a SquadLab export (format: "squadlab-backup")
// The extractor's own schema is kept as-is; validation only checks the fields
// SquadLab relies on.

export const SUPPORTED_SCHEMA_VERSIONS = [2];
export const BACKUP_FORMAT = 'squadlab-backup';
export const BACKUP_VERSION = 1;
const MAX_FILE_BYTES = 500 * 1024 * 1024;

export class ImportError extends Error {
  constructor(message, details = []) {
    super(message);
    this.name = 'ImportError';
    this.details = details;
  }
}

function readFileText(file) {
  if (typeof file.text === 'function') return file.text();
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onload = () => resolve(reader.result);
    reader.onerror = () => reject(reader.error);
    reader.readAsText(file);
  });
}

const isObj = (v) => v !== null && typeof v === 'object' && !Array.isArray(v);
const isInt = (v) => Number.isInteger(v);
const DATE_RE = /^\d{4}-\d{2}-\d{2}$/;

/** 'snapshot' | 'backup' | 'unknown' */
export function detectFileType(obj) {
  if (!isObj(obj)) return 'unknown';
  if (obj.format === BACKUP_FORMAT) return 'backup';
  if ('schema_version' in obj && 'players' in obj && 'career_id' in obj) return 'snapshot';
  return 'unknown';
}

const WRONG_TYPE = {
  snapshot: {
    backup: ['This is a SquadLab app backup, not an FM snapshot.', ['To restore it, use Data → Import app backup.']],
  },
  backup: {
    snapshot: ['This is an FM snapshot, not a SquadLab app backup.', ['To add it to your history, use Data → Import FM snapshot.']],
  },
};

/**
 * Read + parse + check the file is the expected kind.
 * @param {'snapshot'|'backup'} expected
 */
export async function readJsonFile(file, expected) {
  if (!file) throw new ImportError('No file was selected.');
  if (file.size === 0) throw new ImportError('The selected file is empty.');
  if (file.size > MAX_FILE_BYTES) {
    throw new ImportError(`The file is too large (${(file.size / 1048576).toFixed(1)} MB).`);
  }

  let text;
  try {
    text = await readFileText(file);
  } catch {
    throw new ImportError('The file could not be read. If it is in iCloud Drive, make sure it has finished downloading and try again.');
  }

  let obj;
  try {
    obj = JSON.parse(text.replace(/^﻿/, ''));
  } catch (e) {
    throw new ImportError('This file is not valid JSON.', [String(e.message || e)]);
  }

  const type = detectFileType(obj);
  if (type !== expected) {
    const wrong = WRONG_TYPE[expected][type];
    if (wrong) throw new ImportError(wrong[0], wrong[1]);
    throw new ImportError(
      expected === 'snapshot' ? 'This is not an FM snapshot.' : 'This is not a SquadLab app backup.',
      [expected === 'snapshot'
        ? 'Choose a dated JSON generated by the SquadLab save extractor.'
        : 'Choose a file exported with Data → Export app backup.']
    );
  }
  return obj;
}

// ---- FM snapshot -------------------------------------------------------------

/** Returns a list of problems (empty when valid). */
export function snapshotProblems(data) {
  const errors = [];
  if (!isObj(data)) return ['The top level must be an object.'];

  if (!isInt(data.schema_version)) {
    errors.push('Missing "schema_version".');
  } else if (!SUPPORTED_SCHEMA_VERSIONS.includes(data.schema_version)) {
    errors.push(`Unsupported schema_version ${data.schema_version} (supported: ${SUPPORTED_SCHEMA_VERSIONS.join(', ')}).`);
  }
  if (typeof data.career_id !== 'string' || !data.career_id) errors.push('Missing "career_id".');
  if (typeof data.game_date !== 'string' || !DATE_RE.test(data.game_date)) {
    errors.push('Missing or invalid "game_date" (expected YYYY-MM-DD).');
  }
  if (!isObj(data.club) || typeof data.club.name !== 'string' || !data.club.name) {
    errors.push('Missing "club.name".');
  }

  const uids = new Set();
  if (!Array.isArray(data.players)) {
    errors.push('Missing "players" list.');
  } else {
    if (data.players.length === 0) errors.push('The "players" list is empty.');
    let badUid = 0;
    let dupUid = 0;
    for (const p of data.players) {
      if (!isObj(p) || !isInt(p.uid)) { badUid++; continue; }
      if (uids.has(p.uid)) dupUid++;
      uids.add(p.uid);
    }
    if (badUid) errors.push(`${badUid} player record(s) have no numeric "uid".`);
    if (dupUid) errors.push(`${dupUid} duplicate player uid(s) found.`);
  }

  for (const [key, label] of [['squads', 'Squad'], ['shortlists', 'Shortlist']]) {
    if (!Array.isArray(data[key])) { errors.push(`Missing "${key}" list.`); continue; }
    const ids = new Set();
    data[key].forEach((g, i) => {
      if (!isObj(g) || typeof g.id !== 'string' || !g.id) { errors.push(`${label} #${i + 1} has no "id".`); return; }
      if (ids.has(g.id)) errors.push(`Duplicate ${label.toLowerCase()} id "${g.id}".`);
      ids.add(g.id);
      if (!Array.isArray(g.player_uids)) errors.push(`${label} "${g.name || g.id}" has no "player_uids" list.`);
    });
  }
  return errors;
}

/** Non-blocking notes about a valid snapshot. */
export function snapshotWarnings(data) {
  const uids = new Set(data.players.map((p) => p.uid));
  const warnings = [];
  const missing = data.shortlists.reduce((n, l) => n + l.player_uids.filter((u) => !uids.has(u)).length, 0);
  if (missing) warnings.push(`${missing} shortlist entr${missing === 1 ? 'y refers' : 'ies refer'} to players not in the file.`);
  return warnings;
}

export function validateSnapshot(data) {
  const errors = snapshotProblems(data);
  if (errors.length) throw new ImportError('This FM snapshot cannot be imported.', errors);
  return { data, warnings: snapshotWarnings(data) };
}

// ---- App backup ------------------------------------------------------------------

/**
 * Validate a whole backup before anything is touched.
 * Returns { backup, summary } or throws ImportError.
 */
export function validateBackup(b) {
  const errors = [];
  if (b.backup_version !== BACKUP_VERSION) {
    throw new ImportError('This backup was made by a different version of SquadLab.', [
      `Backup format version ${b.backup_version ?? 'missing'}; this app reads version ${BACKUP_VERSION}.`,
    ]);
  }
  const careerId = b.career?.careerId;
  if (typeof careerId !== 'string' || !careerId) errors.push('Missing career identifier.');
  if (!Array.isArray(b.snapshots) || b.snapshots.length === 0) errors.push('The backup contains no snapshots.');
  if (!Array.isArray(b.settings)) errors.push('Missing settings list.');
  if (errors.length) throw new ImportError('This backup is incomplete and cannot be restored.', errors);

  const ids = new Set();
  b.snapshots.forEach((rec, i) => {
    const where = `Snapshot ${i + 1}${rec?.gameDate ? ` (${rec.gameDate})` : ''}`;
    if (!isObj(rec) || !isObj(rec.data)) { errors.push(`${where}: missing data.`); return; }
    const problems = snapshotProblems(rec.data);
    problems.forEach((p) => errors.push(`${where}: ${p}`));
    if (problems.length) return;
    if (rec.data.career_id !== careerId) errors.push(`${where}: belongs to a different career.`);
    if (rec.careerId !== careerId || rec.gameDate !== rec.data.game_date) errors.push(`${where}: header does not match its data.`);
    if (rec.id !== `${careerId}|${rec.gameDate}`) errors.push(`${where}: unexpected id.`);
    if (ids.has(rec.id)) errors.push(`${where}: duplicate in-game date.`);
    ids.add(rec.id);
  });
  b.settings.forEach((s, i) => {
    if (!isObj(s) || typeof s.key !== 'string' || !s.key) errors.push(`Setting ${i + 1}: missing key.`);
  });
  const careerSetting = b.settings.find((s) => s?.key === 'career');
  if (careerSetting && careerSetting.value?.careerId !== careerId) errors.push('Career settings do not match the backup career.');
  if (errors.length) throw new ImportError('This backup failed validation and cannot be restored.', errors);

  const dates = b.snapshots.map((r) => r.gameDate).sort();
  const newest = b.snapshots.find((r) => r.gameDate === dates[dates.length - 1]);
  return {
    backup: b,
    summary: {
      careerId,
      clubName: newest.data.club?.name ?? '—',
      managerName: newest.data.club?.manager_name ?? null,
      count: b.snapshots.length,
      firstDate: dates[0],
      lastDate: dates[dates.length - 1],
      exportedAt: b.exported_at ?? null,
    },
  };
}
